function motor_nastya_plain(string $text): string {
    $text = html_entity_decode(strip_tags(nosmiles($text)), ENT_QUOTES | ENT_HTML5, 'UTF-8');
    $text = preg_replace('/\[(?:\/?[a-z]+)(?:=[^\]]*)?\]/iu', ' ', $text);
    return trim(preg_replace('/\s+/u', ' ', str_replace('ё', 'е', mb_strtolower($text, 'UTF-8'))));
}
